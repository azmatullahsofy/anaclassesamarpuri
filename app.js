    // Enhanced Navigation with scroll effects
    initNavigation() {
        const header = document.querySelector('.header');
        let lastScrollY = window.scrollY;

        // Smooth scrolling for navigation links
        document.querySelectorAll('.nav-link, a[href^="#"]').forEach(link => {
            link.addEventListener('click', (e) => {
                const href = link.getAttribute('href');
                if (href.startsWith('#')) {
                    e.preventDefault();
                    const targetSection = document.querySelector(href);
                    if (targetSection) {
                        targetSection.scrollIntoView({
                            behavior: 'smooth',
                            block: 'start'
                        });
                        
                        // Update active nav link
                        this.updateActiveNavLink(href.substring(1));
                    }
                }
            });
        });

        // Header scroll behavior
        window.addEventListener('scroll', () => {
            const currentScrollY = window.scrollY;
            
            // Header visibility
            if (currentScrollY > lastScrollY && currentScrollY > 100) {
                header.style.transform = 'translateY(-100%)';
            } else {
                header.style.transform = 'translateY(0)';
            }
            
            // Header background opacity
            if (currentScrollY > 50) {
                header.style.background = 'rgba(var(--color-surface), 0.98)';
                header.style.backdropFilter = 'blur(15px)';
            } else {
                header.style.background = 'rgba(var(--color-surface), 0.95)';
                header.style.backdropFilter = 'blur(10px)';
            }

            lastScrollY = currentScrollY;
            
            // Update active section
            this.updateActiveSection();
        });
    }

    updateActiveSection() {
        const sections = document.querySelectorAll('section[id]');
        const navLinks = document.querySelectorAll('.nav-link');
        
        let currentSection = '';
        const scrollPosition = window.scrollY + 150;

        sections.forEach(section => {
            const sectionTop = section.offsetTop;
            const sectionHeight = section.offsetHeight;
            
            if (scrollPosition >= sectionTop && scrollPosition < sectionTop + sectionHeight) {
                currentSection = section.getAttribute('id');
            }
        });

        navLinks.forEach(link => {
            link.classList.remove('active');
            if (link.getAttribute('href') === `#${currentSection}`) {
                link.classList.add('active');
            }
        });
    }

    updateActiveNavLink(sectionId) {
        document.querySelectorAll('.nav-link').forEach(link => {
            link.classList.remove('active');
            if (link.getAttribute('href') === `#${sectionId}`) {
                link.classList.add('active');
            }
        });
    }

    // Advanced Counters with smooth animation
    initCounters() {
        const animateCounter = (element, target, duration = 2000, suffix = '') => {
            const start = performance.now();
            const startValue = 0;
            
            const step = (timestamp) => {
                const progress = Math.min((timestamp - start) / duration, 1);
                const current = startValue + progress * (target - startValue);
                
                if (suffix === '%') {
                    element.textContent = current.toFixed(1) + suffix;
                } else {
                    element.textContent = Math.floor(current) + suffix;
                }
                
                if (progress < 1) {
                    requestAnimationFrame(step);
                }
            };
            
            requestAnimationFrame(step);
        };

        const observeCounters = () => {
            const counterElements = document.querySelectorAll('[data-target]');
            const observer = new IntersectionObserver((entries) => {
                entries.forEach(entry => {
                    if (entry.isIntersecting && !entry.target.classList.contains('counted')) {
                        entry.target.classList.add('counted');
                        const target = parseFloat(entry.target.getAttribute('data-target'));
                        const suffix = entry.target.textContent.includes('%') ? '%' : 
                                     entry.target.textContent.includes('+') ? '+' : '';
                        animateCounter(entry.target, target, 2500, suffix);
                    }
                });
            }, { threshold: 0.5 });

            counterElements.forEach(el => observer.observe(el));
        };

        setTimeout(observeCounters, 500);
    }

